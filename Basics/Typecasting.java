public class Typecasting{
    public static void main(String[] args) {
        Integer x = 10;
        double y = 10.22;
        System.out.println("X : " + (x));
        System.out.println("X : " + (y));
        System.out.println("X : " + (x+y));
        System.out.println(x.getClass().getName());
        System.out.println(x.getClass().getName());
    }
}